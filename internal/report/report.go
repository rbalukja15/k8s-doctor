// Package report renders engine results. The versioned JSON report is the
// single source of truth: terminal output (this package), the HTML report
// (#19) and the eval harness (#21) are all built from it.
package report

import (
	"encoding/json"
	"io"
	"time"

	"github.com/rbalukja15/k8s-doctor/internal/rules"
	"github.com/rbalukja15/k8s-doctor/internal/snapshot"
)

// SchemaVersion is the JSON report format version, validated by
// schema/report.v1.json. Additive changes keep the version; anything that
// removes or renames a field bumps it.
const SchemaVersion = "v1"

// Explanation sources.
const (
	SourceRule = "rule" // the rule's static description (--no-llm or fallback)
	SourceLLM  = "llm"  // generated by the explain layer (#16)
)

// Rule statuses.
const (
	StatusRun    = "run"
	StatusNotRun = "not-run"
)

// Report is the JSON report.
type Report struct {
	SchemaVersion string       `json:"schemaVersion"`
	Tool          Tool         `json:"tool"`
	GeneratedAt   time.Time    `json:"generatedAt"`
	Input         Input        `json:"input"`
	Summary       Summary      `json:"summary"`
	Findings      []Finding    `json:"findings"`
	Groups        []Group      `json:"groups"`
	Rules         []RuleStatus `json:"rules"`
}

// Tool identifies the k8s-doctor build that produced the report.
type Tool struct {
	Name    string `json:"name"`
	Version string `json:"version"`
}

// Input describes what was analyzed.
type Input struct {
	Mode    snapshot.Mode `json:"mode"`
	Cluster string        `json:"cluster,omitempty"`
	Path    string        `json:"path,omitempty"`
	Overlay string        `json:"overlay,omitempty"`
	// LLM reports whether the LLM layer was enabled for this run.
	LLM bool `json:"llm"`
}

// Summary holds counts for dashboards and CI gates.
type Summary struct {
	Total int `json:"total"`
	// BySeverity always has all four severities as keys.
	BySeverity map[string]int `json:"bySeverity"`
	// Worst is the most severe finding's severity, or empty when clean.
	Worst       string `json:"worst,omitempty"`
	RulesRun    int    `json:"rulesRun"`
	RulesNotRun int    `json:"rulesNotRun"`
}

// Finding is an engine finding plus report-only context.
type Finding struct {
	rules.Finding
	Category    string      `json:"category"`
	Explanation Explanation `json:"explanation"`
}

// Explanation is the human-readable "why this matters" for a finding.
type Explanation struct {
	Text   string `json:"text"`
	Source string `json:"source"`
}

// Group is a set of related findings with one root cause (#17). Empty
// until correlation lands.
type Group struct {
	ID         string         `json:"id"`
	Title      string         `json:"title"`
	Severity   rules.Severity `json:"severity"`
	FindingIDs []string       `json:"findingIds"`
	Narrative  string         `json:"narrative,omitempty"`
}

// RuleStatus says whether a rule ran, and why not when it did not.
type RuleStatus struct {
	ID          string          `json:"id"`
	Category    string          `json:"category"`
	Severity    rules.Severity  `json:"severity"`
	Modes       []snapshot.Mode `json:"modes"`
	Description string          `json:"description"`
	Status      string          `json:"status"`
	Reason      string          `json:"reason,omitempty"`
}

// Options are the inputs to Build that do not come from the engine.
type Options struct {
	Version string
	Now     time.Time
	LLM     bool
}

// Build assembles a report from an engine result. Finding and rule order
// follow the engine's deterministic order.
func Build(snap *snapshot.Snapshot, reg *rules.Registry, engine *rules.Engine, res rules.Result, opts Options) *Report {
	r := &Report{
		SchemaVersion: SchemaVersion,
		Tool:          Tool{Name: "k8s-doctor", Version: opts.Version},
		GeneratedAt:   opts.Now.UTC(),
		Input: Input{
			Mode:    snap.Mode,
			Cluster: snap.Source.Cluster,
			Path:    snap.Source.Path,
			LLM:     opts.LLM,
		},
		Findings: make([]Finding, 0, len(res.Findings)),
		Groups:   []Group{},
		Rules:    []RuleStatus{},
	}
	if snap.Source.Overlay != nil {
		r.Input.Overlay = snap.Source.Overlay.Name
	}

	notRun := map[string]string{}
	for _, n := range res.NotRun {
		notRun[n.RuleID] = n.Reason
	}
	for _, rule := range reg.All() {
		st := RuleStatus{
			ID:          rule.ID(),
			Category:    rule.Category(),
			Severity:    engine.Severity(rule),
			Modes:       rule.Modes(),
			Description: rule.Description(),
			Status:      StatusRun,
		}
		if reason, ok := notRun[rule.ID()]; ok {
			st.Status, st.Reason = StatusNotRun, reason
		}
		r.Rules = append(r.Rules, st)
	}

	r.Summary = Summary{BySeverity: map[string]int{}, RulesRun: len(res.RulesRun), RulesNotRun: len(res.NotRun)}
	for _, s := range rules.Severities() {
		r.Summary.BySeverity[s.String()] = 0
	}
	var worst rules.Severity
	for _, f := range res.Findings {
		rule, _ := reg.Get(f.RuleID)
		r.Findings = append(r.Findings, Finding{
			Finding:     f,
			Category:    rule.Category(),
			Explanation: Explanation{Text: rule.Description(), Source: SourceRule},
		})
		r.Summary.BySeverity[f.Severity.String()]++
		worst = max(worst, f.Severity)
	}
	if worst.Valid() {
		r.Summary.Worst = worst.String()
	}
	r.Summary.Total = len(r.Findings)
	return r
}

// WorstSeverity returns the most severe finding's severity and false when
// there are no findings.
func (r *Report) WorstSeverity() (rules.Severity, bool) {
	s, err := rules.ParseSeverity(r.Summary.Worst)
	return s, err == nil
}

// WriteJSON writes the report as indented JSON.
func (r *Report) WriteJSON(w io.Writer) error {
	enc := json.NewEncoder(w)
	enc.SetIndent("", "  ")
	return enc.Encode(r)
}
